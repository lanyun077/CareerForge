const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const ts = require('typescript');
const cache = new Map();
let addresses = [{ address: '8.8.8.8', family: 4 }];
let status = 200;
let responseBody;
let requestCount = 0;
let deferResponses = false;
let abortResponse = false;
const pendingResponses = [];
const limits = [];
function load(file) {
  const resolved = path.resolve(file);
  if (cache.has(resolved)) return cache.get(resolved).exports;
  const mod = { exports: {} };
  cache.set(resolved, mod);
  const code = ts.transpileModule(fs.readFileSync(resolved, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
  const localRequire = (id) => {
    if (id === '@/lib/auth') return { currentOwner: () => 'fixture-owner', limitRequests: (key, max) => limits.push({ key, max }) };
    if (id === '@/lib/jobProvenance') return { issueCollectionReceipt: () => 'test-receipt' };
    if (id === 'node:dns/promises') return { lookup: async (host, options) => { assert.equal(host, 'boards-api.greenhouse.io'); assert.equal(options.family, 4); return addresses; } };
    if (id === 'node:https') return { request: (options, callback) => {
      requestCount++;
      assert.equal(options.hostname, 'boards-api.greenhouse.io');
      assert.equal(options.servername, 'boards-api.greenhouse.io');
      assert.equal(options.agent, false);
      assert.equal(options.family, 4);
      assert.equal(options.path, '/v1/boards/example/jobs/123?content=true');
      options.lookup('boards-api.greenhouse.io', {}, (error, address, family) => { assert.equal(error, null); assert.equal(address, '8.8.8.8'); assert.equal(family, 4); });
      const req = new EventEmitter();
      const respond = () => {
        const res = new EventEmitter();
        res.statusCode = status;
        res.headers = { 'content-type': 'application/json' };
        let destroyed = false;
        res.destroy = () => { destroyed = true; };
        callback(res);
        if (abortResponse) { res.emit('aborted'); return; }
        if (!destroyed) res.emit('data', Buffer.from(responseBody));
        if (!destroyed) res.emit('end');
      };
      req.end = () => { if (deferResponses) pendingResponses.push(respond); else queueMicrotask(respond); };
      return req;
    } };
    if (!id.startsWith('.') && !id.startsWith('@/')) return require(id);
    return load((id.startsWith('@/') ? path.resolve('src', id.slice(2)) : path.resolve(path.dirname(resolved), id)) + '.ts');
  };
  new Function('require', 'module', 'exports', code)(localRequire, mod, mod.exports);
  return mod.exports;
}

async function main() {
  const { parseCollectionUrl, isPublicAddress, postingText, postingCompany, collectJobPosting } = load('src/lib/services/jobCollection.ts');
  const url = 'https://boards.greenhouse.io/example/jobs/123';
  assert.equal(parseCollectionUrl(url + '?utm_source=test').sourceUrl, 'https://job-boards.greenhouse.io/example/jobs/123');
  for (const input of [null, {}, 'http://boards.greenhouse.io/example/jobs/123', 'https://127.0.0.1/example/jobs/123', 'https://boards.greenhouse.io.evil.test/example/jobs/123', 'https://user@boards.greenhouse.io/example/jobs/123', 'https://boards.greenhouse.io:444/example/jobs/123', 'https://boards.greenhouse.io/example/jobs/%31', 'https://boards.greenhouse.io/example/jobs/123/extra']) assert.throws(() => parseCollectionUrl(input), (e) => e.status === 422);
  for (const ip of ['127.0.0.1', '10.0.0.1', '169.254.169.254', '172.16.0.1', '192.168.1.1', '0.0.0.0', '100.64.0.1', '198.18.0.1', '192.0.2.1', '198.51.100.1', '203.0.113.1', '224.0.0.1', '255.255.255.255', '::1', '::ffff:127.0.0.1', '999.1.1.1']) assert.equal(isPublicAddress(ip), false, ip);
  assert.equal(isPublicAddress('8.8.8.8'), true);
  const payload = { id: 123, title: 'Backend Engineer', location: { name: 'Remote' }, content: '&lt;p&gt;Develop Python APIs and maintain PostgreSQL databases.&lt;/p&gt;&lt;script&gt;DO NOT KEEP&lt;/script&gt; Contact me@example.com +1 (555) 123-4567' };
  const clean = postingText(payload, '123');
  assert(!clean.includes('<') && !clean.includes('DO NOT KEEP') && !clean.includes('me@example.com') && !clean.includes('555'));
  const salary = postingText({ ...payload, content: 'Salary 120000-180000 USD; 薪资8000-15000元/月。 电话：010-12345678; Phone: 020 1234 5678; 13812345678' }, '123');
  assert(salary.includes('120000-180000 USD') && salary.includes('8000-15000元/月'));
  assert(!salary.includes('12345678') && !salary.includes('020 1234') && !salary.includes('13812345678'));
  assert.equal(postingCompany({ company_name: '&lt;b&gt;GitLab&lt;/b&gt;' }), 'GitLab');
  assert.equal(postingCompany({}), undefined);
  assert.throws(() => postingText(payload, '124'), (e) => e.status === 502);
  assert.throws(() => postingText({ ...payload, content: 'x'.repeat(13000) }, '123'), (e) => e.status === 422);
  responseBody = JSON.stringify(payload);
  const result = await collectJobPosting(url);
  assert.equal(result.jobText, clean);
  assert.equal(result.provenance.method, 'greenhouse_api');
  assert.equal(result.provenance.availability, 'unknown');
  assert.match(result.provenance.contentHash, /^[a-f0-9]{64}$/);
  assert.equal(result.collectionReceipt, 'test-receipt');
  assert(limits.some((limit) => limit.key.includes('fixture-owner') && limit.max === 6));
  assert(limits.some((limit) => limit.key === 'job-collection:global' && limit.max === 30));
  const before = requestCount;
  addresses = [{ address: '8.8.8.8', family: 4 }, { address: '127.0.0.1', family: 4 }];
  await assert.rejects(collectJobPosting(url), (e) => e.status === 502);
  assert.equal(requestCount, before);
  addresses = [{ address: '8.8.8.8', family: 4 }];
  status = 302;
  await assert.rejects(collectJobPosting(url), (e) => e.status === 502);
  assert.equal(requestCount, before + 1);
  status = 404;
  await assert.rejects(collectJobPosting(url), (e) => e.status === 404);
  status = 200;
  responseBody = 'x'.repeat(512 * 1024 + 1);
  await assert.rejects(collectJobPosting(url), (e) => e.status === 502);
  responseBody = '{invalid';
  await assert.rejects(collectJobPosting(url), (e) => e.status === 502);
  responseBody = JSON.stringify(payload);
  abortResponse = true;
  await assert.rejects(collectJobPosting(url), (e) => e.status === 502);
  abortResponse = false;
  deferResponses = true;
  const pending = [collectJobPosting(url), collectJobPosting(url), collectJobPosting(url)];
  await assert.rejects(collectJobPosting(url), (e) => e.status === 429);
  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(pendingResponses.length, 3);
  pendingResponses.forEach((respond) => respond());
  await Promise.all(pending);
  deferResponses = false;
  assert.equal((await collectJobPosting(url)).jobText, clean);
  console.log('✓ 岗位采集：URL 白名单、内网地址拒绝、TLS 地址绑定、禁止跳转、正文清洗、响应上限、格式校验');
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
